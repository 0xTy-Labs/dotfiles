#!/usr/bin/env node
/**
 * axdots — scripts/gen-rofi-colors.js
 * Reads matugen palette JSON, writes rofi-colors.rasi
 * with the same token names used in AGS CSS tokens.
 *
 * Usage: node gen-rofi-colors.js <palette.json> <output.rasi>
 */

import { readFileSync, writeFileSync } from "fs"
import { resolve } from "path"

const [,, palettePath, outputPath] = process.argv

if (!palettePath || !outputPath) {
  console.error("Usage: gen-rofi-colors.js <palette.json> <output.rasi>")
  process.exit(1)
}

const palette = JSON.parse(readFileSync(resolve(palettePath), "utf8"))
const c = palette.colors

function hexToRgba(hex, alpha) {
  const r = parseInt(hex.slice(1, 3), 16)
  const g = parseInt(hex.slice(3, 5), 16)
  const b = parseInt(hex.slice(5, 7), 16)
  return `rgba(${r}, ${g}, ${b}, ${alpha.toFixed(2)})`
}

const bg    = c.background.hex
const surf  = c.surface_variant.hex
const onS   = c.on_surface_variant.hex
const outV  = c.outline_variant.hex
const prim  = c.primary.hex

const rasi = `/* axdots — rofi-colors.rasi (auto-generated by gen-rofi-colors.js) */

* {
    bg:          ${bg};
    bg_solid:    ${hexToRgba(bg, 0.92)};
    bg_blur:     ${hexToRgba(bg, 0.15)};
    surface:     ${c.surface.hex};
    surface_var: ${surf};
    primary:     ${prim};
    on_primary:  ${c.on_primary.hex};
    secondary:   ${c.secondary.hex};
    tertiary:    ${c.tertiary.hex};
    text:        ${c.on_background.hex};
    text_muted:  ${onS};
    outline:     ${c.outline.hex};
    outline_var: ${outV};
    error:       ${c.error.hex};

    glass_bg:     ${hexToRgba(bg, 0.14)};
    glass_border: ${hexToRgba(outV, 0.30)};
    glass_hover:  ${hexToRgba(c.on_surface.hex, 0.07)};
    accent_soft:  ${hexToRgba(prim, 0.15)};
}
`

writeFileSync(resolve(outputPath), rasi, "utf8")
console.log(`[gen-rofi-colors] Written to ${outputPath}`)
